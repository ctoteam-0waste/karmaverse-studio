import Link from "next/link";
import { notFound } from "next/navigation";
import { readDb } from "@/lib/db";
import { TRANSITIONS } from "@/lib/agents/calendar";
import { lintContent } from "@/lib/agents/content";
import { exportPiece, ADAPTERS } from "@/lib/publishing/adapters";
import { analysisMetrics, scorePosts } from "@/lib/analytics/engine";
import { metricsFor } from "@/lib/analytics/metrics";
import { boostCheck } from "@/lib/agents/engagement";
import { readiness } from "@/lib/publishing/agent";
import { BoostDetails, ScoreBadge } from "@/components/boost";
import { ExtraMedia, VideoMakerForm, VideoPlayer } from "@/components/video-maker";
import { CarouselCard } from "@/components/carousel-maker";
import { VERTICAL, VIDEO_FORMATS } from "@/lib/video/maker";
import { CopyButton } from "@/components/copy-button";
import { ActorField } from "@/components/actor-field";
import { SubmitButton } from "@/components/submit-button";
import { BuddyVideoForm } from "@/components/buddy-video";
import { Flash, fmtDate, fmtWhen, PageHead, PLATFORM_LABEL, SampleBadge, StatusBadge, type SearchParams } from "@/components/ui";
import { approveScheduleAction, savePostNumbersAction, deleteContentAction, makeVideoFromPostAction, publishNowAction, suggestSubtitlesAction, transitionAction, updateContentAction } from "../../actions";

const ACTION_LABEL: Record<string, string> = {
  "needs-review": "Submit for review",
  approved: "Approve",
  draft: "Back to draft",
  scheduled: "Mark scheduled",
  published: "Mark published",
  failed: "Mark failed",
};

export default async function ContentPage({ params, searchParams }: { params: Promise<{ id: string }>; searchParams: SearchParams }) {
  const { id } = await params;
  const q = await searchParams;
  const db = await readDb();
  const piece = db.content.find((c) => c.id === id);
  if (!piece) notFound();
  const brand = db.brands.find((b) => b.id === piece.brandId)!;
  const warnings = lintContent(brand, [piece.hook, piece.caption, piece.description].join("\n"));
  let next = TRANSITIONS[piece.status];
  if (!brand.approvalPolicy.requireReview && piece.status === "draft") next = [...next, "approved"];
  const locked = piece.status === "published";
  const isYouTube = piece.platform === "youtube";
  const boost = boostCheck(piece, scorePosts(analysisMetrics(db.metrics, brand.id)));
  const ready = readiness(piece, db);
  const numberDefs = metricsFor(piece.platform, piece.format);
  const numbersRow = db.metrics.find((m) => m.contentId === piece.id && !m.isSample);
  const canPublishNow = ready.connected && ready.problems.length === 0 && (piece.status === "approved" || piece.status === "scheduled") && !piece.publishingStartedAt;

  return (
    <>
      <PageHead title={piece.topic} intro={<>{PLATFORM_LABEL[piece.platform]} · {piece.format} · {brand.pillars.find((p) => p.id === piece.pillarId)?.name ?? piece.pillarId} · generated by {piece.generatedBy}</>}>
        <StatusBadge status={piece.status} />
        <SampleBadge show={piece.isSample} />
        <Link className="btn secondary" href="/calendar">Calendar</Link>
      </PageHead>
      <Flash params={q} />
      {piece.status === "needs-review" || piece.status === "approved" ? (
        <form action={approveScheduleAction} className="card approve-strip">
          <input type="hidden" name="id" value={piece.id} />
          <input type="hidden" name="back" value={`/content/${piece.id}`} />
          <span>{piece.status === "approved" ? `Approved by ${piece.approvedBy}.` : "This post is waiting for approval."} Planned: <b>{fmtWhen(piece.plannedDate, piece.plannedTime)}</b></span>
          <span className="spacer" />
          <ActorField />
          <SubmitButton className="big ok" pendingText="Saving…">{piece.status === "approved" ? "📅 Schedule it" : piece.plannedDate ? "✅ Approve & schedule" : "✅ Approve"}</SubmitButton>
        </form>
      ) : null}

      {warnings.length ? (
        <div className={`flash ${warnings.some((w) => w.level === "block") ? "err" : "info"}`}>
          <b>Before approval:</b>
          <ul style={{ margin: "0.25rem 0 0" }}>{warnings.map((w) => <li key={w.message}>{w.message}</li>)}</ul>
        </div>
      ) : null}

      <div className="grid two">
        <section className="card">
          <h2>Edit</h2>
          {locked ? <p className="muted">Published content is read-only. Edit it on the platform.</p> : null}
          <form action={updateContentAction} className="stack">
            <input type="hidden" name="id" value={piece.id} />
            <fieldset disabled={locked} style={{ border: 0, padding: 0, margin: 0 }} className="stack">
              <label>{isYouTube ? "Title" : "Hook (first line / first 2 seconds)"}<input name="hook" defaultValue={piece.hook} /></label>
              {!isYouTube ? <label>Caption / post text<textarea name="caption" rows={10} defaultValue={piece.caption} /></label> : <input type="hidden" name="caption" value={piece.caption} />}
              <label>{isYouTube ? "Description" : "Notes (e.g. carousel or document layout)"}<textarea name="description" rows={isYouTube ? 6 : 3} defaultValue={piece.description} /></label>
              <div className="form-grid">
                <label>CTA<input name="cta" defaultValue={piece.cta} /></label>
                <label>Hashtags (space-separated)<input name="hashtags" defaultValue={piece.hashtags.join(" ")} /></label>
                {isYouTube ? <label>Keywords / tags (comma-separated)<input name="keywords" defaultValue={piece.keywords.join(", ")} /></label> : <input type="hidden" name="keywords" value={piece.keywords.join(", ")} />}
                <label>Planned date<input type="date" name="plannedDate" defaultValue={piece.plannedDate ?? ""} /></label>
                <label>Planned time<input name="plannedTime" defaultValue={piece.plannedTime ?? ""} placeholder="19:00" /></label>
              </div>
              <label>Media (one per line: public https links; for YouTube and LinkedIn a file path on this computer also works, e.g. C:\Users\OM\Videos\reel.mp4)<textarea name="mediaUrls" rows={2} defaultValue={piece.mediaUrls.join("\n")} placeholder="https://…/reel.mp4" /></label>
              <label>Thumbnail / cover concept<textarea name="thumbnailConcept" rows={2} defaultValue={piece.thumbnailConcept} /></label>
              <div className="row">
                <ActorField required={false} />
                <button type="submit">Save</button>
              </div>
              <p className="muted">Editing approved or scheduled content sends it back to review.</p>
            </fieldset>
          </form>
        </section>

        <div className="stack">
          <section className="card">
            <h2>Workflow</h2>
            <dl className="kv">
              <dt>Status</dt><dd><StatusBadge status={piece.status} /></dd>
              <dt>Planned</dt><dd>{fmtDate(piece.plannedDate)} {piece.plannedTime ?? ""}</dd>
              <dt>Target</dt><dd>{piece.targetMetric ? `${piece.targetMetric.metric}: ${piece.targetMetric.target}` : "—"}</dd>
              <dt>Approved by</dt><dd>{piece.approvedBy ?? "—"}</dd>
              {piece.publishedUrl ? (<><dt>Live URL</dt><dd><a href={piece.publishedUrl} target="_blank" rel="noreferrer">{piece.publishedUrl}</a></dd></>) : null}
              {piece.failureReason ? (<><dt>Failure</dt><dd>{piece.failureReason}</dd></>) : null}
            </dl>
            <hr />
            {next.length ? (
              <form action={transitionAction} className="stack">
                <input type="hidden" name="id" value={piece.id} />
                <ActorField />
                {next.includes("published") ? <label>Live post URL (needed to mark published)<input name="publishedUrl" type="url" placeholder="https://" /></label> : null}
                {next.includes("failed") ? <label>Failure reason (if marking failed)<input name="failureReason" /></label> : null}
                <label>Note (optional)<input name="note" /></label>
                <div className="row">
                  {next.map((to) => (
                    <button key={to} type="submit" name="to" value={to} className={to === "approved" || to === "published" ? "" : "secondary"}>{ACTION_LABEL[to] ?? to}</button>
                  ))}
                </div>
              </form>
            ) : (
              <p className="muted">This post is published. Its record is kept for analytics.</p>
            )}
          </section>

          {piece.status === "published" ? (
            <section className="card" id="numbers">
              <h2>Add this post&apos;s numbers</h2>
              {numbersRow ? <p className="muted" style={{ marginTop: 0 }}>Saved so far: {Object.entries(numbersRow.metrics).map(([k, v]) => `${numberDefs?.metrics.find((m) => m.key === k)?.label ?? k} ${v}`).join(" · ")}{numbersRow.source === "api" ? " (read from the platform automatically)" : ""}</p> : null}
              {numberDefs ? (
                <form action={savePostNumbersAction} className="form-grid">
                  <input type="hidden" name="id" value={piece.id} />
                  {numberDefs.metrics.map((m) => (
                    <label key={m.key}>{m.label}{m.unit && m.unit !== "count" ? ` (${m.unit})` : ""}<input name={`m_${m.key}`} inputMode="decimal" defaultValue={numbersRow?.metrics[m.key] ?? ""} /></label>
                  ))}
                  <div className="full"><SubmitButton pendingText="Saving…">Save numbers</SubmitButton></div>
                </form>
              ) : <p className="muted">This kind of post isn&apos;t tracked.</p>}
              <p className="muted" style={{ marginBottom: 0 }}>Copy them from the {PLATFORM_LABEL[piece.platform]} app about 3 days after posting. Facebook and YouTube posts made by the app are read automatically.</p>
            </section>
          ) : null}

          <section className="card">
            <h2>Growth Booster <ScoreBadge score={boost.score} /></h2>
            <BoostDetails report={boost} back={`/content/${piece.id}`} editable={!locked} />
          </section>

          {["carousel", "image-post", "document-carousel"].includes(piece.format) ? <CarouselCard piece={piece} locked={locked} /> : null}

          {VIDEO_FORMATS.includes(piece.format) ? (
            <section className="card" id="video">
              <h2>Video</h2>
              <VideoPlayer file={piece.mediaUrls[0]} vertical={VERTICAL.includes(piece.format)} />
              {!locked ? <div style={{ margin: "0.75rem 0" }}><BuddyVideoForm id={piece.id} back={`/content/${piece.id}#video`} hasVideo={piece.mediaUrls.length > 0} /></div> : null}
              <ExtraMedia items={piece.extraMedia} />
              {!locked ? (
                <details open={piece.mediaUrls.length === 0} style={{ marginTop: "0.5rem" }}>
                  <summary style={{ cursor: "pointer" }}>{piece.mediaUrls.length ? "Make a new video from this post" : "Make a video from this post"}</summary>
                  <div style={{ marginTop: "0.5rem" }}>
                    <form action={suggestSubtitlesAction} className="row" style={{ marginBottom: "0.75rem" }}>
                      <input type="hidden" name="id" value={piece.id} />
                      <input name="clip" placeholder="Clip that speaks, e.g. C:\Users\OM\Downloads\pickup-schedule_1080p.mp4" style={{ flex: 1, minWidth: 0 }} aria-label="Clip path for subtitles" />
                      <button type="submit" className="secondary small">Suggest subtitles</button>
                    </form>
                    <VideoMakerForm
                      id={piece.id}
                      subtitles={piece.subtitles}
                      action={makeVideoFromPostAction}
                      label="Make video"
                      hint="Uses the hook, the post text (up to 5 lines) and the CTA. For a fuller script, make a brief in Video Director first. Replacing the video of an approved post sends it back for review."
                    />
                  </div>
                </details>
              ) : null}
            </section>
          ) : null}

          {!locked ? (
            <section className="card">
              <h2>Auto-publish</h2>
              {!ready.connected ? (
                <p className="muted">{PLATFORM_LABEL[piece.platform]} isn&apos;t connected ({ADAPTERS[piece.platform].officialApi}). See <Link href="/publishing">Publishing</Link> to connect it, or post by hand using the text below.</p>
              ) : ready.problems.length ? (
                <div className="flash err" style={{ margin: 0 }}><b>Can&apos;t auto-publish yet:</b> {ready.problems.join(" ")}</div>
              ) : piece.status === "scheduled" ? (
                <p>Goes out automatically at the planned time when auto-publish is on (<Link href="/publishing">Publishing</Link>).</p>
              ) : piece.status === "approved" ? (
                <p>Ready. Mark it scheduled to queue it, or publish it now.</p>
              ) : (
                <p className="muted">Approve this post first. Only approved posts are published.</p>
              )}
              {canPublishNow ? (
                <form action={publishNowAction} className="row" style={{ marginTop: "0.5rem" }}>
                  <input type="hidden" name="id" value={piece.id} />
                  <ActorField />
                  <button type="submit">Publish now to {PLATFORM_LABEL[piece.platform]}</button>
                </form>
              ) : null}
              {piece.publishingStartedAt ? <p className="muted">Publishing started {new Date(piece.publishingStartedAt).toLocaleString("en-IN", { timeZone: "Asia/Kolkata" })}…</p> : null}
            </section>
          ) : null}

          <section className="card">
            <h2>Copy to post by hand <CopyButton text={exportPiece(piece)} /></h2>
            <p className="muted">For platforms that aren&apos;t connected: post this yourself, then mark it published with the live URL.</p>
            <pre style={{ maxHeight: 300, overflow: "auto" }}>{exportPiece(piece)}</pre>
          </section>

          <section className="card">
            <h2>History</h2>
            <ul className="list">
              {[...piece.history].reverse().map((h) => (
                <li key={`${h.at}${h.to}`}><b>{h.from ?? "new"} → {h.to}</b> by {h.by} <span className="muted">{new Date(h.at).toLocaleString("en-IN", { timeZone: "Asia/Kolkata" })}</span>{h.note ? <div className="muted">{h.note}</div> : null}</li>
              ))}
            </ul>
            {!locked ? (
              <form action={deleteContentAction} style={{ marginTop: "0.75rem" }}>
                <input type="hidden" name="id" value={piece.id} />
                <button type="submit" className="danger small">Delete this post</button>
              </form>
            ) : null}
          </section>
        </div>
      </div>
    </>
  );
}
