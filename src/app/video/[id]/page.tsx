import Link from "next/link";
import { notFound } from "next/navigation";
import { readDb } from "@/lib/db";
import { briefToMarkdown } from "@/lib/agents/video";
import { CopyButton } from "@/components/copy-button";
import { Flash, PageHead, PLATFORM_LABEL, type SearchParams } from "@/components/ui";
import { deleteBriefAction, makeVideoFromBriefAction, updateBriefScriptAction } from "../../actions";
import { planProblems, scenesFromBrief, VERTICAL } from "@/lib/video/maker";
import { VideoMakerForm, VideoPlayer } from "@/components/video-maker";

const ts = (s: number) => `${Math.floor(s / 60)}:${String(Math.round(s % 60)).padStart(2, "0")}`;

export default async function BriefPage({ params, searchParams }: { params: Promise<{ id: string }>; searchParams: SearchParams }) {
  const { id } = await params;
  const q = await searchParams;
  const db = await readDb();
  const b = db.briefs.find((x) => x.id === id);
  if (!b) notFound();
  const md = briefToMarkdown(b);
  const brand = db.brands.find((x) => x.id === b.brandId)!;
  const problems = planProblems(scenesFromBrief(brand, b));
  const post = b.contentId ? db.content.find((c) => c.id === b.contentId) : undefined;

  return (
    <>
      <PageHead title={b.title} intro={`${PLATFORM_LABEL[b.platform]} ${b.format} · ${b.durationSec}s · effort ${b.effort.level} (~${b.effort.hours} h) · generated by ${b.generatedBy}`}>
        <CopyButton text={md} label="Copy as Markdown" />
        <Link className="btn secondary" href="/video">All briefs</Link>
      </PageHead>
      <Flash params={q} />
      <div className="grid two" style={{ marginBottom: "1rem" }}>
        <section className="card" id="video">
          <h2>Make the video</h2>
          {problems.length ? (
            <div className="flash err" style={{ margin: "0 0 0.75rem" }}>{problems.join(" ")} Edit the script below.</div>
          ) : null}
          <VideoMakerForm
            id={b.id}
            action={makeVideoFromBriefAction}
            label={b.videoFile ? "Make it again" : "Make video"}
            hint="One captioned scene per script line, a voiceover and an ending call-to-action card. It's attached to this brief's post (a draft is created if there isn't one), ready for review and publishing."
          />
        </section>
        <section className="card">
          <h2>Result</h2>
          {b.videoFile ? (
            <>
              <VideoPlayer file={b.videoFile} vertical={VERTICAL.includes(b.format)} />
              {post ? <p style={{ marginTop: "0.5rem" }}>Attached to <Link href={`/content/${post.id}`}>{post.topic}</Link> ({post.status}).</p> : null}
            </>
          ) : (
            <p className="muted">No video yet. For real-life footage, film it from the storyboard and add the clips as backgrounds, or edit it yourself with the free tools listed below.</p>
          )}
        </section>
      </div>

      <div className="grid two">
        <section className="card">
          <h2>Objective and audience</h2>
          <p>{b.objective}</p>
          <p className="muted">{b.audience}</p>
          <h3>Three opening hooks (test one per post)</h3>
          <ol>{b.hooks.map((h) => <li key={h}>{h}</li>)}</ol>
          <h3>CTA</h3>
          <p>{b.cta}</p>
        </section>
        <section className="card">
          <h2>Titles and thumbnail</h2>
          <ul>{b.titleOptions.map((t) => <li key={t}>{t}</li>)}</ul>
          <p><b>Thumbnail:</b> {b.thumbnailConcept}</p>
          <p><b>Voiceover:</b> {b.voiceover}</p>
          <p><b>Music:</b> {b.musicMood}</p>
          <p><b>Subtitles:</b> {b.subtitleNotes}</p>
        </section>
      </div>

      <section className="card" style={{ marginTop: "1rem" }} id="script">
        <h2>Edit script</h2>
        <form action={updateBriefScriptAction} className="stack">
          <input type="hidden" name="id" value={b.id} />
          <label>
            One line per scene: <code>voiceover | on-screen text</code>. Replace every [bracketed] part.
            <textarea name="script" rows={Math.min(14, b.script.length + 2)} defaultValue={b.script.map((l) => `${l.voiceover} | ${l.onScreenText}`).join("\n")} />
          </label>
          <label>Call to action (last card)<input name="cta" defaultValue={b.cta} /></label>
          <div><button type="submit" className="secondary">Save script</button></div>
        </form>
      </section>

      <section className="card" style={{ marginTop: "1rem" }}>
        <h2>Script</h2>
        <div className="table-wrap">
          <table>
            <thead><tr><th>Time</th><th>Voiceover</th><th>On-screen text</th></tr></thead>
            <tbody>{b.script.map((l) => <tr key={l.start}><td>{ts(l.start)}–{ts(l.end)}</td><td>{l.voiceover}</td><td>{l.onScreenText}</td></tr>)}</tbody>
          </table>
        </div>
      </section>

      <section className="card" style={{ marginTop: "1rem" }}>
        <h2>Storyboard</h2>
        <div className="table-wrap">
          <table>
            <thead><tr><th>#</th><th>Time</th><th>Visual</th><th>Camera</th><th>Framing</th><th>Transition</th><th>B-roll</th></tr></thead>
            <tbody>{b.storyboard.map((s) => <tr key={s.scene}><td>{s.scene}</td><td>{ts(s.start)}–{ts(s.end)}</td><td>{s.visual}</td><td>{s.camera}</td><td>{s.framing}</td><td>{s.transition}</td><td>{s.bRoll || "—"}</td></tr>)}</tbody>
          </table>
        </div>
      </section>

      <div className="grid two" style={{ marginTop: "1rem" }}>
        <section className="card">
          <h2>Editing instructions</h2>
          <ul>{b.editingInstructions.map((e) => <li key={e}>{e}</li>)}</ul>
        </section>
        <section className="card">
          <h2>Free tools</h2>
          <ul>{b.freeTools.map((t) => <li key={t}>{t}</li>)}</ul>
          <form action={deleteBriefAction}><input type="hidden" name="id" value={b.id} /><button className="danger small">Delete brief</button></form>
        </section>
      </div>
    </>
  );
}
